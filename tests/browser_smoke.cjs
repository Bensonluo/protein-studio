const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async()=>{
  const launchOptions={headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']};
  if(process.env.CHROME_PATH)launchOptions.executablePath=process.env.CHROME_PATH;
  const browser=await chromium.launch(launchOptions);
  const errors=[],checks=[];
  const page=await browser.newPage({viewport:{width:1512,height:1080},deviceScaleFactor:1});
  page.on('pageerror',error=>errors.push(error.message));
  const base=process.env.STUDIO_URL||'http://127.0.0.1:8765';
  const waitStructure=()=>page.waitForFunction(()=>document.querySelector('#molecule-viewer canvas')&&document.querySelector('#viewer-loading')?.classList.contains('hidden'),null,{timeout:20000});
  try {
    await page.goto(base,{waitUntil:'domcontentloaded'});
    await waitStructure();
    if(!await page.locator('#pae-canvas').count()){await page.locator('[data-view="jobs"]').click();await page.locator('#job-search').fill('Polyubiquitin');await page.locator('tbody tr[data-job-id]').first().click();await waitStructure();}
    assert.equal(await page.locator('#pae-canvas').count(),1);
    assert.equal(await page.locator('.residue').count(),229);
    checks.push('real AFDB structure, 229 residues, pLDDT and PAE rendered');
    await page.screenshot({path:'artifacts/studio-desktop.png',fullPage:true});
    await page.screenshot({path:'artifacts/studio-preview.png'});
    await page.locator('[data-style="stick"]').click();
    await page.waitForTimeout(300);
    await page.locator('[data-style="surface"]').click();
    await page.waitForTimeout(1200);
    await page.locator('[data-style="cartoon"]').click();
    await page.locator('#color-mode').selectOption('chain');
    await page.locator('#color-mode').selectOption('confidence');
    checks.push('cartoon, ball-and-stick, molecular surface and coloring controls');
    await page.locator('[data-residue="5"]').click();
    assert.match(await page.locator('#sequence-selection').textContent(),/A:6/);
    checks.push('residue sequence selects and locates the actual 3D residue');
    await page.locator('#reset-view').click();
    const snapshotPromise=page.waitForEvent('download');await page.locator('#snapshot-view').click();
    const snapshot=await snapshotPromise;await snapshot.saveAs('artifacts/structure-export.png');
    assert.ok(fs.statSync('artifacts/structure-export.png').size>1000);
    checks.push('3D PNG snapshot exported');
    const downloadPromise=page.waitForEvent('download');await page.locator('.viewer-tabline a').click();
    const download=await downloadPromise;await download.saveAs('artifacts/downloaded-structure.pdb');
    assert.match(fs.readFileSync('artifacts/downloaded-structure.pdb','utf8'),/ATOM/);
    checks.push('original structure file downloaded');
    await page.locator('#new-job-button').click();
    await page.waitForFunction(()=>document.querySelector('#sequence-input').value.length>100);
    assert.equal(await page.locator('#job-samples').inputValue(),'1');
    await page.locator('[data-engine="alphafold3"]').click();
    assert.equal(await page.locator('#submit-job-button').isDisabled(),true);
    await page.locator('[data-engine="reference"]').click();
    const originalSequence=await page.locator('#sequence-input').inputValue();
    await page.locator('#job-name').fill('UI validation check');
    await page.locator('#sequence-input').fill(originalSequence.replace(/C\s*$/,'X'));
    await page.locator('#submit-job-button').click();
    await page.waitForFunction(()=>document.querySelector('#form-error').textContent.length>0);
    checks.push('invalid scientific input rejected and unconfigured real engines disabled');
    await page.locator('#sequence-input').fill(originalSequence);
    const testName='UI reference test '+Date.now();await page.locator('#job-name').fill(testName);
    await page.locator('#submit-job-button').click();
    await page.waitForFunction(()=>!document.querySelector('#job-dialog').open);
    await waitStructure();
    assert.match(await page.locator('.job-detail-bar strong').textContent(),/UI reference test/);
    checks.push('submit → queue → real artifact replay → structure/metrics end-to-end');
    await page.locator('[data-view="jobs"]').click();
    await page.locator('#job-search').fill(testName);
    assert.equal(await page.locator('tbody tr[data-job-id]').count(),1);
    await page.locator('tbody tr[data-job-id]').click();await waitStructure();
    checks.push('persisted task list, search and result navigation');
    await page.locator('#new-job-button').click();await page.locator('#input-mode').selectOption('batch');await page.locator('#sequence-input').fill('>copy-1\n'+originalSequence.split('\n').slice(1).join('')+'\n>copy-2\n'+originalSequence.split('\n').slice(1).join(''));await page.locator('#job-name').fill('UI batch '+Date.now());await page.locator('#submit-job-button').click();await page.waitForFunction(()=>!document.querySelector('#job-dialog').open);await waitStructure();checks.push('multi-record FASTA submits independent batch jobs');
    await page.locator('#structure-file').setInputFiles(path.join(process.cwd(),'fixtures/1CRN.pdb'));await page.locator('#confirm-import').click();
    await page.waitForFunction(()=>document.querySelector('.job-detail-bar strong')?.textContent==='1CRN.pdb');await waitStructure();
    assert.equal(await page.locator('.residue').count(),46);
    assert.equal(await page.locator('#pae-canvas').count(),0);
    assert.match(await page.locator('.right-column').textContent(),/暂无模型置信度/);
    checks.push('experimental PDB import persisted; B factors never shown as pLDDT');
    await page.locator('[data-view="sources"]').click();
    assert.ok(await page.locator('.source-card').count()>=6);
    await page.screenshot({path:'artifacts/research-sources.png',fullPage:true});
    await page.locator('[data-view="environment"]').click();
    assert.ok(await page.locator('.environment-card').count()>=4);
    await page.locator('[data-view="pipeline"]').click();
    assert.equal(await page.locator('.architecture-node').count(),6);
    checks.push('research citations, engine diagnostics and six-stage pipeline views');
    await page.locator('[data-view="jobs"]').click();await page.locator('#job-search').fill('Polyubiquitin');
    await page.locator('tbody tr[data-job-id]').first().click();await waitStructure();
    await page.setViewportSize({width:390,height:844});await page.waitForTimeout(400);
    const dimensions=await page.evaluate(()=>({width:document.documentElement.clientWidth,scrollWidth:document.documentElement.scrollWidth}));
    assert.ok(dimensions.scrollWidth<=dimensions.width+1,JSON.stringify(dimensions));
    await page.screenshot({path:'artifacts/studio-mobile.png',fullPage:true});
    checks.push('390px mobile layout has no horizontal page overflow');
    assert.deepEqual(errors,[]);
    const report={date:'2026-10-23',status:'passed',checks,consoleErrors:errors,actualGpuInference:false,browser:'Chromium / Chrome with WebGL software rendering in test'};
    fs.writeFileSync('artifacts/browser-verification.json',JSON.stringify(report,null,2)+'\n');
    console.log(JSON.stringify(report));
  } catch(error) {
    await page.screenshot({path:'artifacts/studio-error.png',fullPage:true}).catch(()=>{});
    console.error(JSON.stringify({checks,errors,viewerText:await page.locator('#viewer-loading').textContent().catch(()=>null)}));
    throw error;
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1});
