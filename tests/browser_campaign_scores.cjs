'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.STUDIO_URL||'http://127.0.0.1:8765';
const output=path.resolve('artifacts');
const checks=[],created=[],errors=[];
let browser;
async function api(url,options={}){const response=await fetch(base+url,{...options,headers:{'Content-Type':'application/json',...options.headers}});const value=await response.json();assert.ok(response.ok,JSON.stringify(value));return value;}
(async()=>{
  browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1536,height:1080},deviceScaleFactor:1});page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/#campaigns',{waitUntil:'domcontentloaded'});
  await page.waitForSelector('#campaign-form');
  // Wait until the initial data refresh has re-rendered the monitor, otherwise
  // the re-render resets form values that were filled in the meantime.
  await page.waitForSelector('#campaign-monitor .batch-dashboard, #campaign-monitor .batch-empty');
  const ubiquitin=await api('/api/examples/ubiquitin-afdb');
  const fasta=[...Array(5)].map((_,i)=>`>泛素候选_${i+1}\n${ubiquitin.chains[0].sequence}\n`).join('');
  await page.locator('#campaign-name').fill('置信度排序验证 · 公开结构回放');
  await page.locator('#campaign-file').setInputFiles({name:'score-mixed.fasta',mimeType:'text/plain',buffer:Buffer.from(fasta)});
  const campaignResponse=page.waitForResponse(r=>r.url()===base+'/api/campaigns'&&r.request().method()==='POST');
  await page.locator('#campaign-submit').click();const campaign=await (await campaignResponse).json();created.push(campaign.id);
  await page.waitForFunction(id=>document.querySelector('#campaign-select')?.value===id&&document.querySelector('[data-stage-filter="completed"] strong')?.textContent==='5',campaign.id,{timeout:45000});
  await page.waitForSelector('#campaign-score-sort');
  const sortOptions=await page.locator('#campaign-score-sort option').allTextContents();
  assert.deepEqual(sortOptions,['默认顺序','排名分 降序','ipTM 降序','pTM 降序','平均 pLDDT 降序']);checks.push('Confidence sort selector offers ranking/ipTM/pTM/pLDDT descending options');
  const detail=await api('/api/campaigns/'+campaign.id);
  const chipCount=await page.locator('[data-score-filter]').count();
  assert.equal(chipCount,Number(detail.metrics.iptmScoredTargets)>0?2:0,'ipTM threshold chips match campaign ipTM coverage');
  checks.push('EBI ipTM threshold chips appear only when the campaign actually has ipTM scores');
  const bands=detail.metrics.scoreBands;
  const plddtBanded=bands.plddt.veryHigh+bands.plddt.confident+bands.plddt.low+bands.plddt.veryLow;
  assert.equal(plddtBanded,5,'all delivered reference targets land in a pLDDT band');
  await page.waitForSelector('.campaign-score-bands .campaign-score-band');
  const bandText=await page.locator('.campaign-score-bands').innerText();
  assert.ok(bandText.includes('pLDDT'),'band summary shows the pLDDT section');
  assert.ok(!bandText.includes('ipTM'),'band summary hides the ipTM section when unscored');
  const segCount=await page.locator('.campaign-band-bar .campaign-band-seg').count();
  const swatchCount=await page.locator('.campaign-band-swatch').count();
  assert.ok(segCount>0,'distribution bar draws at least one segment');
  assert.equal(swatchCount,segCount,'legend swatches match the drawn segments');
  checks.push('Dashboard confidence band summary reflects ledger band metrics');
  checks.push('Distribution bar segments and legend swatches stay in sync');
  const expected=await api('/api/campaigns/'+campaign.id+'/items?sort=plddt&stage=completed');
  const expectedOrder=expected.items.map(item=>item.name);
  const scored=expected.items.filter(item=>item.resultScores&&item.resultScores.meanPlddt!=null);
  assert.ok(scored.length>0,'reference replay must publish mean pLDDT scores');
  assert.equal(expectedOrder.length,5);
  await page.selectOption('#campaign-score-sort','plddt');
  await page.waitForFunction(order=>[...document.querySelectorAll('.batch-items tbody .campaign-target-link')].map(el=>el.textContent.trim()).join('|')===order.join('|'),expectedOrder,{timeout:20000});
  const domOrder=[...await page.locator('.batch-items tbody .campaign-target-link').allTextContents()].map(t=>t.trim());
  assert.deepEqual(domOrder,expectedOrder);checks.push('pLDDT descending sort orders all 5 delivered targets identically to the ledger API');
  const cellValues=await page.locator('.batch-items tbody .campaign-score-detail').allTextContents();
  assert.equal(cellValues.length,5);assert.ok(cellValues.every(text=>text.includes('pLDDT')));checks.push('Every delivered row shows its confidence metrics without opening the target inspector');
  await page.locator('.batch-items tbody .campaign-target-link').first().click();
  await page.waitForSelector('.campaign-inspect-scores');
  const inspectText=await page.locator('.campaign-inspect-scores').innerText();
  assert.ok(inspectText.includes('平均 pLDDT'));
  assert.ok(inspectText.includes('置信度评分'));
  await page.locator('#campaign-inspect-close').click();
  checks.push('Target inspector shows the published confidence scores section');
  const ranked=await api('/api/campaigns/'+campaign.id+'/items?sort=ranking');
  assert.deepEqual(ranked.items.map(item=>item.name),expectedOrder);checks.push('Ledger ranking sort agrees with pLDDT ordering for reference replay results');
  const exportText=await (await fetch(base+'/api/campaigns/'+campaign.id+'/export?sort=plddt')).text();
  const exportRows=exportText.trim().split('\n').map(line=>JSON.parse(line));
  assert.equal(exportRows.length,5);
  assert.deepEqual(exportRows.map(row=>row.name),expectedOrder);
  assert.ok(exportRows.every(row=>row.resultScores&&row.resultScores.meanPlddt!=null));
  checks.push('Scored JSONL export matches the pLDDT listing order and carries resultScores');
  const deliveredHref=await page.locator('[data-campaign-export="completed"]').getAttribute('href');
  assert.match(deliveredHref,/sort=plddt/);
  checks.push('Delivered-export link follows the active score sort');
  await page.screenshot({path:path.join(output,'campaign-scores.png'),fullPage:true});
  assert.deepEqual(errors,[]);checks.push('No browser JavaScript errors');
  fs.writeFileSync(path.join(output,'campaign-scores-verification.json'),JSON.stringify({date:new Date().toISOString(),base,checks,createdCampaignIds:created,errors,note:'Reference replay validates the confidence ledger, sorting, UI contract and scored export only; no new model prediction or GPU benchmark.'},null,2));
  console.log(JSON.stringify({passed:checks.length,checks,createdCampaignIds:created},null,2));
})().catch(error=>{console.error(error);process.exitCode=1}).finally(async()=>{await browser?.close()});
