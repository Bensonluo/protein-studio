// Real local HTTP controller/worker verification. No API response is mocked.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.STUDIO_URL||'http://127.0.0.1:8765';
const output=path.resolve('artifacts');
let browser;
(async()=>{
  const checks=[],errors=[];
  const cluster=await (await fetch(base+'/api/cluster')).json();
  assert.equal(cluster.enabled,true);
  assert.equal(cluster.planned.localGpuCards,16);
  const nodes=cluster.nodes.filter(n=>['local-demo','aliyun-demo'].includes(n.id));
  assert.equal(nodes.length,2);
  for(const node of nodes){assert.equal(node.status,'online');assert.equal(node.modelLoads,0);assert.ok(node.processedTargets>1);assert.ok(node.pid>0);}
  assert.ok(cluster.transfers.length>0);
  assert.ok(cluster.events.some(e=>e.type==='ready'&&e.message.includes('Lease revoked')));
  const recovery=JSON.parse(fs.readFileSync(path.join(output,'hybrid-recovery-verification.json'),'utf8'));
  const campaignId=recovery.campaignId;
  assert.ok(campaignId);
  browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1536,height:1120},deviceScaleFactor:1});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/#cluster',{waitUntil:'domcontentloaded'});
  await page.waitForSelector('.cluster-node');
  await page.locator('#cluster-auto').uncheck();
  assert.equal(await page.locator('.cluster-node').count(),2);
  assert.equal(await page.locator('.cluster-metric strong').first().textContent(),'16');
  assert.equal(await page.getByText('REFERENCE · 无 GPU 推理',{exact:true}).count(),2);
  for(const node of nodes)assert.ok((await page.locator('#cluster-nodes').textContent()).includes(String(node.pid)));
  checks.push('Actual two registered resident processes, PID/processed counts and demo labels; planned 16 GPUs remain separate');
  assert.equal(await page.locator('.cluster-flow-step').count(),5);
  assert.ok(await page.locator('#cluster-batches tbody tr').count()>1);
  const detail=page.locator('#cluster-transfers details').first();
  await detail.locator('summary').click();
  assert.match(await detail.locator('dd code').textContent(),/^[a-f0-9]{64}$/);
  assert.ok((await page.locator('#cluster-events').textContent()).includes('失联目标的租约已回收'));
  checks.push('Real batches, byte counts, full transfer SHA-256 and lease-recovery timeline rendered');
  await page.screenshot({path:path.join(output,'cluster-live.png'),fullPage:true});
  await page.locator('[data-cluster-location="aliyun"]').click();
  await page.locator('#cluster-search').fill('aliyun');
  assert.equal(await page.locator('.cluster-node').count(),1);
  await page.locator('#cluster-refresh').click();
  await page.waitForFunction(()=>!document.querySelector('#cluster-refresh').disabled);
  assert.equal(await page.locator('#cluster-search').inputValue(),'aliyun');
  assert.equal(await page.locator('.cluster-node').count(),1);
  checks.push('Location and node search preserved across actual API refresh');
  await page.locator('#cluster-search').fill('');
  await page.locator('[data-cluster-location="all"]').click();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:path.join(output,'cluster-live-mobile.png'),fullPage:true});
  checks.push('Actual cluster page has no horizontal page overflow at 390px');
  await page.setViewportSize({width:1536,height:1120});
  await page.locator('[data-view="campaigns"]').click();
  await page.waitForSelector('#campaign-placement');
  assert.deepEqual(await page.locator('#campaign-placement option').evaluateAll(options=>options.map(o=>o.value)),['hybrid','local','aliyun']);
  await page.waitForFunction(id=>[...document.querySelector('#campaign-select').options].some(o=>o.value===id),campaignId);
  await page.selectOption('#campaign-select',campaignId);
  await page.waitForFunction(()=>document.querySelector('[data-stage-filter="completed"] strong')?.textContent==='18');
  assert.ok((await page.locator('.batch-dashboard').textContent()).includes('常驻节点批量执行'));
  assert.equal(await page.locator('[data-campaign-item]').count(),18);
  await page.screenshot({path:path.join(output,'campaign-resident-live.png'),fullPage:true});
  checks.push('Campaign shows all 18 recovered targets delivered, placement options and resident-worker path');
  await page.locator('[data-campaign-item]').first().click();
  await page.waitForSelector('#viewer-loading.hidden',{state:'attached',timeout:20000});
  assert.ok(await page.locator('#molecule-viewer canvas').count());
  assert.equal(await page.locator('.residue').count(),46);
  await page.locator('.execution-details summary').click();
  const provenance=await page.locator('.execution-details').textContent();
  assert.match(provenance,/执行节点 \/ 位置/);assert.match(provenance,/(local-demo|aliyun-demo)/);assert.match(provenance,/PID \d+/);
  const download=await page.locator('.viewer-tabline a').getAttribute('href');
  const structure=await fetch(base+download);assert.equal(structure.status,200);assert.match(await structure.text(),/ATOM/);
  checks.push('Recovered campaign result opens real 46-residue structure with worker/batch/PID provenance and downloadable coordinates');
  await page.locator('[data-view="pipeline"]').click();
  assert.equal(await page.locator('.architecture-node').count(),6);
  assert.match(await page.locator('#content').textContent(),/常驻/);
  await page.locator('[data-view="environment"]').click();
  await page.waitForSelector('.environment-card');
  assert.match(await page.locator('#content').textContent(),/常驻节点模式/);
  checks.push('Pipeline and environment pages describe the active resident-worker execution mode');
  assert.deepEqual(errors,[]);
  const report={date:new Date().toISOString(),base,status:'passed',scope:'Actual loopback HTTP controller plus two real resident reference worker subprocesses; no mocked API, no native model/GPU/cloud execution',checks,errors,nodeSnapshot:nodes,campaignId,screenshots:['cluster-live.png','cluster-live-mobile.png','campaign-resident-live.png'],actualGpuInference:false,actualCloudConnection:false};
  fs.writeFileSync(path.join(output,'hybrid-live-browser-verification.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify({passed:checks.length,checks,errors}));
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{await browser?.close();});
