  await page.keyboard.press('Escape');
  checks.push('Resident batch inspector links individual targets into full pipeline/lease/event detail');
  await page.locator('[data-view="cluster"]').click();await page.waitForSelector('.cv-topology');
  await page.locator('[data-cv-location="aliyun"]').click();
  assert.equal(await page.locator('.cluster-node').count(),1);
  assert.match(await page.locator('.cluster-node').textContent(),/阿里云/);
  await page.locator('[data-cluster-location="all"]').click();
  checks.push('Topology execution pools are actionable location filters');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.notEqual(await page.locator('.cv-route-motion').evaluate(el=>getComputedStyle(el).animationName),'cv-packets');
  await page.emulateMedia({reducedMotion:'no-preference'});
  checks.push('Reduced-motion preference disables routing animation');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'artifacts/pipeline-rich-mobile.png',fullPage:true});
  checks.push('390px topology, queue ribbon and routing diagnostics have no page overflow');
