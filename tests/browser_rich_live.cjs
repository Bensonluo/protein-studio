  assert.equal(await page.locator('.cv-gpu-slot').count(),16);
  assert.equal(await page.locator('.cv-gpu-slot.registered').count(),0);
  assert.equal(await page.locator('.cv-stage').count(),7);
  assert.equal(await page.locator('.cv-routing>div').count(),2);
  checks.push('Live topology reflects running queue, shows 16 planned slots and zero invented GPU devices');
  await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'artifacts/pipeline-rich-active.png',fullPage:true});
  await page.locator('.cv-batch-link').first().click();await page.waitForSelector('#cv-batch-dialog[open]');
  assert.ok(await page.locator('.cv-member').count()>0);
  const target=page.locator('.cv-member').first();const itemId=await target.getAttribute('data-cv-item');
  await target.click();await page.waitForSelector('#campaign-inspector[open]');
